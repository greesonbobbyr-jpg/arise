// Core logging flow on demo data: picker, PREVIOUS, PR, rest, warmup, reload survival, finish, routine editor, kg, erase.
// run: node e2e/cdp.js "http://127.0.0.1:8765/index.html?demo#workout" "" 390 e2e/core-flow.js
const path = require('path');
module.exports = async (ctx) => {
  const { evalFn, shot, nav, sleep } = ctx;
  const { check, click, type, txt, st, dismissNotify, done, SHOTS } = require('./lib')(ctx);
  await click('#start-empty');
  let s = await st();
  check('active workout created', !!s.active && s.active.entries.length === 0);
  await click('#add-ex'); await sleep(400);
  await type('#psearch', 'press');
  const rows = await evalFn(`Array.from(document.querySelectorAll('[data-pick]')).map(r=>r.dataset.pick)`);
  check('most-used first (bb_bench top)', rows[0] === 'bb_bench', rows[0]);
  await click('[data-pick="bb_bench"]'); await click('[data-pick="bb_ohp"]');
  check('multi-select count label', /Add 2 exercises/.test(await txt('#padd')));
  await click('#padd'); await sleep(300);
  s = await st();
  check('two exercises added', s.active.entries.length === 2 && s.active.entries[0].exId === 'bb_bench');
  check('sets prefilled from last session', s.active.entries[0].sets.length === 3 && s.active.entries[0].sets[0].w > 0, s.active.entries[0].sets[0]);
  const prev0 = s.active.entries[0].sets[0];
  check('PREVIOUS column shows last session', (await txt('[data-prev="0:0"]')) === prev0.w + ' × ' + prev0.r, await txt('[data-prev="0:0"]'));
  await type('[data-w="0:0"]', 190); await type('[data-r="0:0"]', 8);
  await click('[data-ck="0:0"]'); await sleep(300); await dismissNotify();
  s = await st();
  check('set marked done', s.active.entries[0].sets[0].done === true);
  check('rest timer started (120s default)', s.active.rest && s.active.rest.total === 120, s.active.rest && s.active.rest.total);
  check('PR toast fired', /NEW PR/.test(await txt('#toast')), await txt('#toast'));
  check('live e1RM + PR badge', /PR/.test(await txt('#exstats-0')), await txt('#exstats-0'));
  await type('[data-w="0:1"]', ''); await type('[data-r="0:1"]', '');
  await click('[data-prev="0:1"]');
  s = await st();
  check('tap PREVIOUS fills set 2', s.active.entries[0].sets[1].w > 0 && s.active.entries[0].sets[1].r > 0, s.active.entries[0].sets[1]);
  await click('[data-warm="0:2"]');
  check('warmup row labelled W', (await txt('[data-warm="0:2"]')) === 'W');
  await click('#restplus'); s = await st();
  check('+15s extends rest', s.active.rest.total === 135, s.active.rest.total);
  await nav('http://127.0.0.1:8765/index.html'); await sleep(500);
  s = await st();
  check('active workout survives reload', !!s.active && s.active.entries[0].sets[0].done === true);
  await click('#finish'); await sleep(300);
  check('finish confirms first', /Finish workout\?/.test(await txt('#modal')));
  const before = await st();
  await click('#modal .acts button.primary'); await sleep(500);
  await shot(path.join(SHOTS, 'summary.png'));
  s = await st();
  check('session saved', s.sessions.length === before.sessions.length + 1 && s.active === null);
  const last = s.sessions[s.sessions.length - 1];
  check('only completed sets kept', last.entries.length === 1 && last.entries[0].sets.length === 1, last.entries);
  check('PR recorded', s.game.prs.length === before.game.prs.length + 1);
  await click('#modal .acts button.primary'); await sleep(300);
  if (await evalFn(`document.querySelector('#rankup').classList.contains('on')`)) { await sleep(1500); await click('#rankup'); }
  await click('[data-tab="routines"]'); await click('#new-routine');
  await type('#r-name', 'Push Day');
  await click('#r-add'); await sleep(300);
  await click('[data-pick="bb_incline"]'); await click('[data-pick="db_lateral"]'); await click('#padd'); await sleep(300);
  await type('[data-rs="0"]', 4); await type('[data-rr="0"]', 8); await type('[data-rx="0"]', 12);
  await click('#r-save'); await sleep(300);
  s = await st();
  const r = s.routines[s.routines.length - 1];
  check('routine saved with 4 × 8–12', r && r.name === 'Push Day' && r.items[0].sets === 4 && r.items[0].reps === 8 && r.items[0].repsMax === 12, r && r.items[0]);
  await click('[data-tab="profile"]'); await click('#p-units button[data-v="kg"]'); await sleep(200);
  check('kg toggle converts bodyweight', (await evalFn(`document.querySelector('#p-bw').value`)) === '81.6');
  await click('[data-tab="progress"]'); await sleep(300);
  check('progress renders in kg', /kg e1RM/.test(await txt('#screen')));
  await click('[data-tab="profile"]'); await click('#p-units button[data-v="lb"]'); await sleep(200);
  await click('#p-data-toggle'); await sleep(200);
  await click('#p-erase'); await sleep(200); await click('#modal .acts button:not(.danger)'); await sleep(200);
  check('erase cancel keeps data', (await st()).sessions.length > 0);
  await click('#p-erase'); await click('#modal .acts button.danger'); await sleep(200);
  check('second confirmation shown', /Last chance/.test(await txt('#modal')));
  await click('#modal .acts button.danger'); await sleep(300);
  s = await st();
  check('erase clears everything', s.sessions.length === 0 && s.routines.length === 0 && s.game.xp === 0);
  done('core flow');
};
